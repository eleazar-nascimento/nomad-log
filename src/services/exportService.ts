/**
 * Gera arquivo CSV com todas as despesas da viagem
 */
export function generateExpensesCSV(
  expenses: Expense[],
  baseCurrency: string
): string {
  const headers = [
    "Data",
    "Hora",
    "Categoria",
    "Descricao",
    "Local",
    "Valor_Original",
    "Moeda_Original",
    `Valor_Convertido_${baseCurrency}`,
    "Forma_Pagamento",
    "Notas",
  ];

  const rows = expenses.map((e) => [
    `"${e.date}"`,
    `"${e.time}"`,
    `"${e.category}"`,
    `"${(e.description || "").replace(/"/g, '""')}"`,
    `"${(e.locationName || "").replace(/"/g, '""')}"`,
    e.amount.toFixed(2),
    `"${e.currency}"`,
    e.convertedAmountBase.toFixed(2),
    `"${e.paymentMethod}"`,
    `"${(e.notes || "").replace(/"/g, '""')}"`,
  ]);

  // Adiciona BOM (\uFEFF) para que o Excel abra acentos UTF-8 perfeitamente
  return "\uFEFF" + [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
}

/**
 * Gera backup completo da viagem em JSON estruturado
 */
export function generateTripJSON(
  trip: Trip,
  expenses: Expense[],
  waypoints: Waypoint[],
  journal: JournalEntry[],
  packing: PackingItem[]
): string {
  const backup = {
    app: "NomadLog",
    version: "1.0.0",
    exportedAt: new Date().toISOString(),
    trip,
    summary: {
      totalSpentBase: expenses.reduce((s, e) => s + e.convertedAmountBase, 0),
      totalExpensesCount: expenses.length,
      totalWaypointsCount: waypoints.length,
      totalMemoriesCount: journal.length,
      totalPackingItemsCount: packing.length,
    },
    expenses,
    waypoints,
    journal,
    packing,
  };

  return JSON.stringify(backup, null, 2);
}

/**
 * Gera um relatório formatado em Markdown para ler, salvar ou colar em notas/WhatsApp
 */
export function generateTripMarkdownReport(
  trip: Trip,
  expenses: Expense[],
  waypoints: Waypoint[],
  journal: JournalEntry[],
  packing: PackingItem[],
  locale: "pt" | "en" = "pt"
): string {
  const isPt = locale === "pt";
  const totalSpent = expenses.reduce((s, e) => s + e.convertedAmountBase, 0);
  const remaining = trip.totalBudgetBase - totalSpent;
  const packedCount = packing.filter((p) => p.packed).length;

  const title = isPt ? "Relatório de Viagem & Despesas" : "Trip & Expense Report";
  const generatedBy = isPt
    ? "Gerado pelo NomadLog (100% Offline)"
    : "Generated by NomadLog (100% Offline)";

  return `# 🧭 ${trip.title}
*${title} — ${generatedBy}*

---

### 📍 ${isPt ? "Dados da Viagem" : "Trip Overview"}
- **${isPt ? "Destino" : "Destination"}:** ${trip.destination}
- **${isPt ? "Período" : "Dates"}:** ${trip.startDate} ${isPt ? "até" : "to"} ${trip.endDate}
- **${isPt ? "Moeda Base" : "Base Currency"}:** ${trip.baseCurrency}
- **${isPt ? "Moedas em Trânsito" : "Local Currencies"}:** ${trip.localCurrencies.join(", ")}

---

### 💰 ${isPt ? "Resumo Financeiro" : "Financial Summary"}
- **${isPt ? "Orçamento Total Definido" : "Total Budget"}:** ${formatMoney(trip.totalBudgetBase, trip.baseCurrency)}
- **${isPt ? "Total Gasto Acumulado" : "Total Spent"}:** ${formatMoney(totalSpent, trip.baseCurrency)}
- **${isPt ? "Saldo Restante" : "Remaining Balance"}:** ${formatMoney(remaining, trip.baseCurrency)}
- **${isPt ? "Quantidade de Lançamentos" : "Number of Expenses"}:** ${expenses.length}

#### ${isPt ? "Lançamentos de Despesas" : "Expense Records"}:
${
  expenses.length === 0
    ? `*${isPt ? "Nenhum gasto registrado ainda." : "No expenses recorded yet."}*`
    : expenses
        .map(
          (e) =>
            `- [${e.date} ${e.time}] **${e.description}**: ${formatMoney(e.amount, e.currency)} (≈ ${formatMoney(e.convertedAmountBase, trip.baseCurrency)}) • *${e.locationName}* [${e.category}]`
        )
        .join("\n")
}

---

### 🗺️ ${isPt ? "Itinerário & Paradas Concluídas" : "Itinerary & Completed Stops"} (${waypoints.length} ${isPt ? "paradas" : "stops"})
${
  waypoints.length === 0
    ? `*${isPt ? "Nenhuma parada adicionada ainda." : "No waypoints added yet."}*`
    : waypoints
        .map(
          (w) =>
            `- **[Dia ${w.dayIndex} - ${w.time}]** ${w.title} (${w.locationName}) ${
              w.elevationMeters ? `• 🏔️ ${w.elevationMeters}m alt.` : ""
            } [${w.status.toUpperCase()}]`
        )
        .join("\n")
}

---

### 🎒 ${isPt ? "Status da Bagagem" : "Packing Status"}
- ${packedCount} / ${packing.length} ${isPt ? "itens empacotados" : "items packed"} (${Math.round(
    packing.length > 0 ? (packedCount / packing.length) * 100 : 0
  )}%)

---

### 📖 ${isPt ? "Memórias do Diário de Bordo" : "Journal Highlights"} (${journal.length} ${isPt ? "relatos" : "entries"})
${
  journal.length === 0
    ? `*${isPt ? "Nenhuma memória de bordo gravada ainda." : "No journal entries recorded yet."}*`
    : journal
        .map(
          (j) => `#### ✍️ ${j.title} (${j.date})
*${j.location} • Humor: ${j.mood}*
> "${j.content}"
`
        )
        .join("\n\n")
}

---
*NomadLog • Offline-First Travel Logbook & Multi-Currency Tracker*
`;
}

/**
 * Exporta arquivo nativo no Android/iOS via expo-file-system e expo-sharing,
 * ou faz download automático no navegador Web.
 */
export async function triggerFileExport(
  content: string,
  filename: string,
  mimeType: string
): Promise<boolean> {
  // 1. Android & iOS Nativos
  if (Platform.OS !== "web") {
    try {
      const fileUri = `${FileSystem.cacheDirectory}${filename}`;
      await FileSystem.writeAsStringAsync(fileUri, content, {
        encoding: FileSystem.EncodingType.UTF8,
      });

      const isAvailable = await Sharing.isAvailableAsync();
      if (isAvailable) {
        await Sharing.shareAsync(fileUri, {
          mimeType,
          dialogTitle: `NomadLog - ${filename}`,
        });
        return true;
      } else {
        await Share.share({
          message: content,
          title: filename,
        });
        return true;
      }
    } catch (e) {
      console.warn("[ExportService] Erro ao exportar nativo:", e);
      try {
        await Share.share({
          message: content,
          title: filename,
        });
        return true;
      } catch (fallbackErr) {
        console.warn("[ExportService] Fallback de compartilhamento falhou:", fallbackErr);
        return false;
      }
    }
  }

  // 2. Ambiente Web
  if (Platform.OS === "web" && typeof document !== "undefined") {
    try {
      const blob = new Blob([content], { type: mimeType });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      return true;
    } catch (e) {
      console.warn("[ExportService] Falha ao fazer download na Web:", e);
    }
  }

  // 3. Fallback Clipboard na Web
  if (typeof navigator !== "undefined" && navigator.clipboard) {
    try {
      await navigator.clipboard.writeText(content);
      return true;
    } catch (err) {
      console.warn("[ExportService] Falha ao copiar para clipboard:", err);
    }
  }

  return false;
}
